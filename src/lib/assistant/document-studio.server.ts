function pdfEscape(str: string): string {
  return str
    .replace(/[^\x20-\x7e]/g, " ")
    .replace(/\\/g, "\\\\")
    .replace(/\(/g, "\\(")
    .replace(/\)/g, "\\)");
}

function wrapText(line: string, maxChars = 84): string[] {
  const words = line.trim().split(/\s+/).filter(Boolean);
  if (words.length === 0) return [""];
  const out: string[] = [];
  let cur = "";
  for (const w of words) {
    if ((cur + " " + w).trim().length > maxChars) {
      if (cur) out.push(cur);
      cur = w;
    } else {
      cur = (cur + " " + w).trim();
    }
  }
  if (cur) out.push(cur);
  return out;
}

/** #11 Genuine Standards-Compliant %PDF-1.4 Document Generator */
export function buildPdfDocumentBuffer(input: {
  title: string;
  author?: string;
  sections: { heading: string; paragraphs: string[] }[];
}): Buffer {
  const lines: { text: string; bold: boolean; size: number }[] = [
    { text: input.title, bold: true, size: 16 },
    { text: `Author: ${input.author || "Noctis Universal Assistant v1.0"} | Generated: ${new Date().toISOString()}`, bold: false, size: 9 },
    { text: "", bold: false, size: 11 },
  ];
  for (const sec of input.sections) {
    lines.push({ text: sec.heading, bold: true, size: 13 });
    for (const p of sec.paragraphs) {
      for (const wrapped of wrapText(p, 86)) {
        lines.push({ text: wrapped, bold: false, size: 10.5 });
      }
      lines.push({ text: "", bold: false, size: 6 });
    }
  }

  // Paginate lines (~42 lines per page)
  const pagesLines: typeof lines[] = [];
  const perPage = 44;
  for (let i = 0; i < lines.length; i += perPage) {
    pagesLines.push(lines.slice(i, i + perPage));
  }
  if (pagesLines.length === 0) pagesLines.push([{ text: input.title, bold: true, size: 16 }]);

  // Object allocation: 1=Catalog, 2=Pages, 3=FontReg, 4=FontBold, then pairs (Page, Content)
  const objects: string[] = [];
  const pageObjNums: number[] = [];

  // Placeholder slots 1..4
  objects.push(""); // 1 Catalog
  objects.push(""); // 2 Pages
  objects.push("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"); // 3
  objects.push("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>"); // 4

  for (let pIdx = 0; pIdx < pagesLines.length; pIdx++) {
    const pLines = pagesLines[pIdx]!;
    const cmds: string[] = ["BT"];
    let y = 745;
    for (const ln of pLines) {
      if (ln.text) {
        const f = ln.bold ? "/F2" : "/F1";
        cmds.push(`${f} ${ln.size} Tf`);
        cmds.push(`1 0 0 1 54 ${y} Tm`);
        cmds.push(`(${pdfEscape(ln.text)}) Tj`);
      }
      y -= Math.round(ln.size + 4.5);
    }
    cmds.push("ET");
    const streamStr = cmds.join("\n");
    const pageObjNum = objects.length + 1;
    const contentObjNum = pageObjNum + 1;
    pageObjNums.push(pageObjNum);
    objects.push(
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${contentObjNum} 0 R >>`,
    );
    objects.push(`<< /Length ${Buffer.byteLength(streamStr, "latin1")} >>\nstream\n${streamStr}\nendstream`);
  }

  objects[0] = `<< /Type /Catalog /Pages 2 0 R >>`;
  objects[1] = `<< /Type /Pages /Kids [${pageObjNums.map((n) => `${n} 0 R`).join(" ")}] /Count ${pageObjNums.length} >>`;

  const chunks: Buffer[] = [Buffer.from("%PDF-1.4\n%\xFF\xFF\xFF\xFF\n", "latin1")];
  const offsets: number[] = [0];
  let cursor = chunks[0]!.length;

  for (let i = 0; i < objects.length; i++) {
    offsets.push(cursor);
    const body = Buffer.from(`${i + 1} 0 obj\n${objects[i]}\nendobj\n`, "latin1");
    chunks.push(body);
    cursor += body.length;
  }

  const xrefOffset = cursor;
  const xrefLines = [
    `xref`,
    `0 ${objects.length + 1}`,
    `0000000000 65535 f `,
    ...offsets.slice(1).map((o) => `${String(o).padStart(10, "0")} 00000 n `),
    `trailer`,
    `<< /Size ${objects.length + 1} /Root 1 0 R >>`,
    `startxref`,
    `${xrefOffset}`,
    `%%EOF\n`,
  ];
  chunks.push(Buffer.from(xrefLines.join("\n"), "latin1"));
  return Buffer.concat(chunks);
}

/** Simple ZIP central directory extractor to parse uploaded .xlsx sheets without external deps. */
function extractZipEntries(buf: Buffer): Record<string, Buffer> {
  const files: Record<string, Buffer> = {};
  let pos = 0;
  while (pos + 30 < buf.length) {
    if (buf.readUInt32LE(pos) !== 0x04034b50) break;
    const method = buf.readUInt16LE(pos + 8);
    const compSize = buf.readUInt32LE(pos + 18);
    const nameLen = buf.readUInt16LE(pos + 26);
    const extraLen = buf.readUInt16LE(pos + 28);
    const nameStart = pos + 30;
    const name = buf.subarray(nameStart, nameStart + nameLen).toString("utf8");
    const dataStart = nameStart + nameLen + extraLen;
    const comp = buf.subarray(dataStart, dataStart + compSize);
    if (method === 0) files[name] = comp;
    else if (method === 8) {
      try {
        files[name] = inflateRawSync(comp);
      } catch {
        /* ignore malformed deflate */
      }
    }
    pos = dataStart + compSize;
  }
  return files;
}

/** #21 Parse uploaded CSV, TSV, JSON, TXT, or .xlsx workbook into uniform tabular headers/rows + text summary */
export function parseUploadedTabularFile(filename: string, rawTextOrBase64: string) {
  const lower = filename.toLowerCase();
  if (lower.endsWith(".xlsx")) {
    const rawBuf = Buffer.from(rawTextOrBase64.replace(/^data:[^;]+;base64,/, ""), "base64");
    const zipEntries = extractZipEntries(rawBuf);
    const sharedXml = zipEntries["xl/sharedStrings.xml"]?.toString("utf8") || "";
    const shared = [...sharedXml.matchAll(/<t[^>]*>([\s\S]*?)<\/t>/g)].map((m) => m[1]!);
    const sheetKey = Object.keys(zipEntries).find((k) => /^xl\/worksheets\/sheet1\.xml$/i.test(k)) || "";
    const sheetXml = sheetKey ? zipEntries[sheetKey]!.toString("utf8") : "";
    const rows: string[][] = [];
    for (const rowM of sheetXml.matchAll(/<row[^>]*>([\s\S]*?)<\/row>/g)) {
      const cells: string[] = [];
      for (const cM of rowM[1]!.matchAll(/<c([^>]*)>([\s\S]*?)<\/c>/g)) {
        const attrs = cM[1] || "";
        const inner = cM[2] || "";
        const tMatch = inner.match(/<t[^>]*>([\s\S]*?)<\/t>/);
        const vMatch = inner.match(/<v>([\s\S]*?)<\/v>/);
        if (tMatch) cells.push(tMatch[1]!);
        else if (/t="s"/.test(attrs) && vMatch) cells.push(shared[parseInt(vMatch[1]!, 10)] ?? vMatch[1]!);
        else if (vMatch) cells.push(vMatch[1]!);
        else cells.push("");
      }
      if (cells.length > 0) rows.push(cells);
    }
    const headers = rows[0] || [];
    return { format: "xlsx", headers, rows: rows.slice(1), rowCount: Math.max(0, rows.length - 1) };
  }

  if (lower.endsWith(".json")) {
    const parsed = JSON.parse(rawTextOrBase64);
    const arr = Array.isArray(parsed) ? parsed : Array.isArray(parsed?.rows) ? parsed.rows : [parsed];
    const headers = arr.length > 0 && typeof arr[0] === "object" && arr[0] ? Object.keys(arr[0]) : ["value"];
    const rows = arr.map((r: Record<string, unknown>) => headers.map((h) => String(r?.[h] ?? "")));
    return { format: "json", headers, rows, rowCount: rows.length };
  }

  const delim = lower.endsWith(".tsv") ? "\t" : ",";
  const lines = rawTextOrBase64.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  const splitLine = (ln: string) => ln.split(delim).map((c) => c.trim().replace(/^"|"$/g, ""));
  const headers = lines[0] ? splitLine(lines[0]) : [];
  const rows = lines.slice(1).map(splitLine);
  return { format: lower.endsWith(".tsv") ? "tsv" : "csv", headers, rows, rowCount: rows.length };
}

/** #88 Format-Preserving Structured Markdown Section Editor */
export function editDocumentSectionPreservingFormat(input: {
  markdown: string;
  targetHeading: string;
  replacementBody: string;
}) {
  const lines = input.markdown.split(/\r?\n/);
  const headingNorm = input.targetHeading.trim().toLowerCase();
  const out: string[] = [];
  let inTarget = false;
  let replaced = false;

  for (const ln of lines) {
    const hdr = ln.match(/^(#{1,6})\s+(.+)$/);
    if (hdr) {
      const title = hdr[2]!.trim().toLowerCase();
      if (inTarget) inTarget = false;
      out.push(ln);
      if (title === headingNorm || title.includes(headingNorm)) {
        inTarget = true;
        replaced = true;
        out.push(input.replacementBody.trim());
      }
      continue;
    }
    if (!inTarget) out.push(ln);
  }
  if (!replaced) {
    out.push("", `## ${input.targetHeading}`, input.replacementBody.trim());
  }
  const updatedMarkdown = out.join("\n");
  return {
    replacedExistingSection: replaced,
    updatedMarkdown,
    sha256: sha256Sync(updatedMarkdown),
  };
}

/** #33 / #54 Long-Document Comparison & Contradiction/Temporal Analyzer */
export function compareTwoDocuments(input: {
  titleA: string;
  textA: string;
  titleB: string;
  textB: string;
}) {
  const linesA = input.textA.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  const linesB = input.textB.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  const setA = new Set(linesA);
  const setB = new Set(linesB);
  const added = linesB.filter((l) => !setA.has(l));
  const removed = linesA.filter((l) => !setB.has(l));
  const sharedCount = linesB.filter((l) => setA.has(l)).length;

  const contradictions = detectCrossSourceContradictions([
    ...linesA.slice(0, 15).map((l) => `[${input.titleA}] ${l}`),
    ...linesB.slice(0, 15).map((l) => `[${input.titleB}] ${l}`),
  ]);
  const temporalA = analyzeTemporalSequence(input.textA);
  const temporalB = analyzeTemporalSequence(input.textB);

  return {
    titleA: input.titleA,
    titleB: input.titleB,
    lineCounts: { docA: linesA.length, docB: linesB.length, sharedLines: sharedCount, addedLines: added.length, removedLines: removed.length },
    addedSample: added.slice(0, 10),
    removedSample: removed.slice(0, 10),
    contradictionAnalysis: contradictions,
    temporalComparison: { docADates: temporalA.isoDatesOrdered, docBDates: temporalB.isoDatesOrdered },
  };
}
