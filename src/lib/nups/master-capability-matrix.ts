export const NOCTIS_MASTER_CAPABILITY_MATRIX: NupsCapabilityEntry[] = [
  NOCTIS_NUPS_ORCHESTRATOR,
  ...NOCTIS_20_INDUSTRY_ENGINES,
  ...NOCTIS_10_SCIENTIFIC_ENGINES,
  ...NOCTIS_10_CROSS_PLATFORM_CAPABILITIES,
];

export function filterCapabilityMatrix(opts: {
  category?: NupsEngineCategory | "ALL";
  phase?: NupsExpansionPhase | "ALL";
  search?: string;
} = {}): NupsCapabilityEntry[] {
  const cat = opts.category || "ALL";
  const phase = opts.phase || "ALL";
  const q = (opts.search || "").trim().toLowerCase();

  return NOCTIS_MASTER_CAPABILITY_MATRIX.filter((e) => {
    if (cat !== "ALL" && e.category !== cat) return false;
    if (phase !== "ALL" && e.phase !== phase) return false;
    if (q) {
      const hay = [
        e.id,
        e.name,
        e.capabilitiesSummary,
        ...e.existingModules,
        ...e.authoritativeSources,
        ...e.deterministicRules,
        ...e.triggerKeywords,
      ]
        .join(" ")
        .toLowerCase();
      if (!hay.includes(q)) return false;
    }
    return true;
  });
}

export function getMasterCapabilityMatrixSummary() {
  const byCategory = {
    ORCHESTRATOR: NOCTIS_MASTER_CAPABILITY_MATRIX.filter((e) => e.category === "ORCHESTRATOR").length,
    INDUSTRY: NOCTIS_20_INDUSTRY_ENGINES.length,
    SCIENTIFIC_TECHNICAL: NOCTIS_10_SCIENTIFIC_ENGINES.length,
    CROSS_PLATFORM: NOCTIS_10_CROSS_PLATFORM_CAPABILITIES.length,
  };
  const byStatus = {
    LIVE_WIRED: NOCTIS_MASTER_CAPABILITY_MATRIX.filter((e) => e.status === "LIVE_WIRED").length,
    EXISTING_ENGINE_WIRED_VIA_NUPS: NOCTIS_MASTER_CAPABILITY_MATRIX.filter(
      (e) => e.status === "EXISTING_ENGINE_WIRED_VIA_NUPS",
    ).length,
    NEWLY_BUILT_GAP_CLOSED: NOCTIS_MASTER_CAPABILITY_MATRIX.filter(
      (e) => e.status === "NEWLY_BUILT_GAP_CLOSED",
    ).length,
  };
  return {
    totalCataloged: NOCTIS_MASTER_CAPABILITY_MATRIX.length,
    byCategory,
    byStatus,
    phases: NUPS_EXPANSION_PHASES,
  };
}

export function renderMasterCapabilityMatrixMarkdown(opts: {
  category?: NupsEngineCategory | "ALL";
} = {}): string {
  const items = filterCapabilityMatrix({ category: opts.category || "ALL" });
  const summary = getMasterCapabilityMatrixSummary();
  const lines = [
    `# Noctis Master Capability Matrix (${summary.totalCataloged} Engines: 1 NUPS + 20 Industries + 10 Scientific/Technical + 10 Cross-Platform)`,
    `- **Wiring Breakdown:** \`${summary.byStatus.LIVE_WIRED}\` Live-Wired · \`${summary.byStatus.EXISTING_ENGINE_WIRED_VIA_NUPS}\` Existing Engines Wired via NUPS · \`${summary.byStatus.NEWLY_BUILT_GAP_CLOSED}\` Newly Built Domain Gap Closures (Insurance, Real Estate, Government Admin)`,
    "",
    "| ID | Engine | Category | Priority Phase | Authoritative Sources | Key Deterministic Rule | Primary Module | Status |",
    "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
    ...items.map(
      (e) =>
        `| \`${e.id}\` | **${e.name}** | ${e.category} | ${e.phase.replace("PHASE_", "P").replace(/_/g, " ")} | ${e.authoritativeSources.slice(0, 2).join("; ")} | ${e.deterministicRules[0]} | \`${e.existingModules[0]}\` | ${e.status} |`,
    ),
  ];
  return lines.join("\n");
}
